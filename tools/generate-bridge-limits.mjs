import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const sourcePath = path.join(repoRoot, 'contracts', 'bridge-protocol-limits.json');
const csharpPath = path.join(repoRoot, 'Services', 'BridgeProtocolLimits.g.cs');
const typescriptPath = path.join(
  repoRoot,
  'frontend',
  'agent',
  'src',
  'contracts',
  'bridgeProtocolLimits.generated.ts'
);
const check = process.argv.includes('--check');
const limits = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const required = [
  'agentWireEnvelopeCharacters',
  'terminalWireEnvelopeCharacters',
  'agentPromptTextCharacters',
  'terminalInputBytes',
  'imageBytes',
  'promptImageBytes',
  'promptImageCount',
  'avatarBytes'
];
if (limits.schemaVersion !== 1) throw new Error('Unsupported bridge limits schemaVersion.');
for (const key of required) {
  if (!Number.isSafeInteger(limits[key]) || limits[key] <= 0) {
    throw new Error(`Bridge limit '${key}' must be a positive safe integer.`);
  }
}

function pascalCase(value) {
  return value[0].toUpperCase() + value.slice(1);
}

const csharp = `// <auto-generated />\nnamespace PSX.Services;\n\npublic static class BridgeProtocolLimits\n{\n${required
  .map((key) => `    public const int ${pascalCase(key)} = ${limits[key]};`)
  .join('\n')}\n}\n`;

const typescript = `// Generated from contracts/bridge-protocol-limits.json.\n// Run node tools/generate-bridge-limits.mjs after changing the source contract.\nexport const BridgeProtocolLimits = Object.freeze({\n${required
  .map((key) => `  ${key}: ${limits[key]}`)
  .join(',\n')}\n});\n`;

function synchronize(file, content) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      console.error(`[bridge-limits] generated file is stale: ${path.relative(repoRoot, file)}`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
}

synchronize(csharpPath, csharp);
synchronize(typescriptPath, typescript);
if (!process.exitCode) console.log(`[bridge-limits] ${check ? 'verified' : 'generated'} C# and TypeScript constants.`);
